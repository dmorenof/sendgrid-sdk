<?php

declare(strict_types=1);

namespace SendGridSDK\Resources\V3\VerifiedSenders;

final class Verify extends \SendGridSDK\Client
{
    private const array GET_BY_TOKEN = [
        'method' => 'GET',
        'path' => '/v3/verified_senders/verify/{token}',
        'security' => [
            [
                'BearerAuth' => [],
            ],
        ],
        'success' => [
            204,
        ],
        'errors' => [
            401 => '\\SendGridSDK\\DTOs\\Verified\\SendersError\\Response',
            403 => '\\SendGridSDK\\DTOs\\Verified\\SendersError\\Response',
            404 => '\\SendGridSDK\\Responses\\Errors\\Status404Variant11Response',
            500 => '\\SendGridSDK\\Responses\\Errors\\Status500Response',
        ],
        'errorResponses' => [
            401 => [
                'type' => '\\SendGridSDK\\DTOs\\Verified\\SendersError\\Response',
                'schemaNullable' => false,
            ],
            403 => [
                'type' => '\\SendGridSDK\\DTOs\\Verified\\SendersError\\Response',
                'schemaNullable' => false,
            ],
            404 => [
                'type' => '\\SendGridSDK\\Responses\\Errors\\Status404Variant11Response',
                'schemaNullable' => false,
            ],
            500 => [
                'type' => '\\SendGridSDK\\Responses\\Errors\\Status500Response',
                'schemaNullable' => false,
            ],
        ],
    ];

    /**
     * Verify Sender Request
     *
     * **This endpoint allows you to verify a sender requests.**
     *
     * The token is generated by SendGrid and included in a verification email delivered to the address that's pending verification.
     */
    public function getByToken(string $token): void
    {
        $this->executeArguments(self::operation(self::GET_BY_TOKEN), path: ['token' => $token]);
        return;
    }
}
